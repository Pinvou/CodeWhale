import assert from 'node:assert/strict';
import { test } from 'node:test';
import { adminComponent, adminDOM } from './helpers/admin-component-fixture.mjs';
import { adminPlatformCopy } from '../src/shared/i18n.js';

for (const language of ['zh', 'en', 'ja']) test('SMS unknown replay ignores the edited invalid draft and retains the original key: ' + language, async t => {
  const { SettingsWorkspace } = await adminComponent('SettingsWorkspace.jsx');
  const ui = await adminDOM(t), calls = [];
  const configuration = { revision: 3, enabled: true, provider_id: 'aliyun-managed', credential_profile: 'aliyun-default', sign_name: 'Fixture sign', templates: { REGISTER: 'Fixture register', LOGIN: 'Fixture login', PROFILE_MOBILE: 'Fixture mobile', PASSWORD_RESET: 'Fixture reset' }, available_profiles: [{ provider_id: 'aliyun-managed', profile_id: 'aliyun-default', configured: true }] };
  const client = { financeSessionEpoch: 1, authorizationVersions: { context_version: 1, platform_authorization_version: 1 }, smsConfiguration: async () => configuration, updateSMSConfiguration: async (command, key) => {
    calls.push({ command: structuredClone(command), key });
    if (calls.length === 1) throw Object.assign(new Error('unknown write'), { status: 503 });
    if (calls.length === 2) throw Object.assign(new Error('authentication required'), { status: 401, code: 'RECENT_AUTHENTICATION_REQUIRED' });
    return { ...command, revision: command.expected_revision + 1 };
  } };
  await ui.render(SettingsWorkspace, { client, copy: adminPlatformCopy[language], language, permissions: ['platform.sms-config.read', 'platform.sms-config.manage'], onLanguageChange() {} });
  const form = () => ui.document.querySelector('.adm-sms-form');
  const reason = () => ui.document.querySelector('.adm-sms-reason textarea');
  const save = () => ui.document.querySelector('.adm-sms-form-actions button[type=submit]');
  await ui.change(reason(), 'Controlled original reason');
  assert.equal(save().disabled, false);
  assert.equal(save().hasAttribute('formnovalidate'), false, 'new writes keep native validation');
  await ui.submit(form());
  assert.equal(calls.length, 1);
  await ui.change(reason(), '');
  await ui.change(ui.document.querySelector('.adm-sms-template input'), '');
  assert.equal(save().disabled, false, 'edited draft cannot block the original unknown request');
  assert.equal(save().hasAttribute('formnovalidate'), true, 'native required fields cannot block the replay button');
  await ui.submit(form());
  assert.equal(calls.length, 2);
  assert.deepEqual(calls[1], calls[0]);
  assert.equal(calls[1].command.reason, 'Controlled original reason');
  assert.equal(calls[1].command.templates.REGISTER, 'Fixture register');
  await ui.click(ui.document.querySelector('.adm-sms-error button'));
  assert.equal(reason().value, '', 'an explicit configuration reread resets the editable reason');
  assert.equal(save().disabled, false, 'the reread cannot block the frozen unknown attempt');
  await ui.submit(form());
  assert.equal(calls.length, 3);
  assert.deepEqual(calls[2], calls[0]);
  assert.equal(reason().value, '');
  assert.equal(save().hasAttribute('formnovalidate'), false, 'confirmed replay returns to ordinary draft validation');
  assert.equal(save().disabled, true);
  await ui.change(reason(), 'Controlled distinct next reason');
  await ui.submit(form());
  assert.equal(calls.length, 4);
  assert.notEqual(calls[3].key, calls[0].key);
  assert.equal(calls[3].command.expected_revision, 4);
  assert.equal(calls[3].command.reason, 'Controlled distinct next reason');
  assert.equal(save().hasAttribute('formnovalidate'), false);
});
