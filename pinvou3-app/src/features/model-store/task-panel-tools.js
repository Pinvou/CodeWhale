/**
 * 任务卡「更多」菜单里各条目的显示条件，抽成纯函数给渲染测试真实覆盖。
 *
 * 背景（2026-10-16 评审阻塞项 4）：这些条件原先内联在 JSX 里，SSR 渲染测试
 * 既不执行点击事件（菜单收起，条目永不出现），旧测试就在断言"失败卡上**没有**
 * 导出按钮"——标题与断言相反，且把门控改成 true 测试照样全绿。条件抽出来之后，
 * 门控逻辑有了不依赖交互的真实断言；组件里只留布局。
 */

/**
 * 「导出日志（可外发）」只在失败的、且有运行日志可导出（runId）的任务上提供。
 * 它存在的理由是脱敏分了两道：落盘那份留着路径和内网地址（不留就没法诊断），
 * 导出那份把它们一起抹掉。没有这个入口，更严的那一道就没有任何出口。
 * 正在跑的任务不给：还没有"要反馈的失败"，多一个按钮只是噪声。
 *
 * @param {{status?: string, runId?: string|null}} task 任务对象。
 * @returns {boolean} 是否渲染导出日志菜单项。
 */
export function exportLogEligible(task) {
  return task?.status === 'error' && Boolean(task?.runId);
}
