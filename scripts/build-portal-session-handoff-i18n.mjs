#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { accountPlatformCopy } from '../pinvou3-app/src/shared/account-platform-i18n.js';
import { supportedLocales } from '../pinvou3-app/src/shared/supported-locales.js';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(repositoryRoot, 'account-platform', 'internal', 'portal', 'static', 'assets', 'portal-session-handoff-i18n.js');
const catalog = Object.fromEntries(supportedLocales.map(locale => [locale, accountPlatformCopy[locale].sessionHandoff]));
const output = `// Generated by scripts/build-portal-session-handoff-i18n.mjs; do not edit.\nexport const portalSessionHandoffCopy = ${JSON.stringify(catalog, null, 2)};\n`;

if (process.argv.includes('--check')) {
  const deployed = await readFile(outputPath, 'utf8');
  if (deployed !== output) throw new Error('portal_session_handoff_i18n_artifact_stale');
} else {
  await writeFile(outputPath, output, 'utf8');
}
