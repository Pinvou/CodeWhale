import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'account-platform/internal/portal/credential-handoff.v1.js');
const outputPath = path.join(root, 'account-platform/internal/portal/credential_handoff_hash_generated.go');
const source = await readFile(sourcePath);
const digest = createHash('sha256').update(source).digest('base64');
const generated = `// Code generated by scripts/build-credential-handoff.mjs; DO NOT EDIT.\n\npackage portal\n\nconst credentialHandoffScriptSHA256 = "${digest}"\n`;

if (process.argv.includes('--check-deployment')) {
  const staticRoot = path.join(root, 'account-platform/internal/portal/static');
  const entries = await readdir(staticRoot, { recursive: true, withFileTypes: true });
  const scripts = entries.filter((entry) => entry.isFile() && /\.(?:html|js)$/u.test(entry.name));
  for (const entry of scripts) {
    const contents = await readFile(path.join(entry.parentPath, entry.name), 'utf8');
    if (/serviceWorker\s*\.\s*register\s*\(/u.test(contents)) {
      process.stderr.write(`credential handoff release blocked: Service Worker registration may cover /credential-handoff in ${path.relative(root, path.join(entry.parentPath, entry.name))}\n`);
      process.exitCode = 1;
    }
  }
} else if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    process.stderr.write('credential handoff script digest is stale; run node scripts/build-credential-handoff.mjs\n');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated);
}
