import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const read = relative => readFileSync(new URL(`../../${relative}`, import.meta.url), 'utf8');

test('Portal lineage logout has a non-overlapping, evidenced two-phase rollout', () => {
  const compose = read('deploy/compose/compose.yaml');
  const production = read('deploy/production/compose.business.yaml');
  const values = read('deploy/helm/account-platform/values.yaml');
  const schema = JSON.parse(read('deploy/helm/account-platform/values.schema.json'));
  const template = read('deploy/helm/account-platform/templates/app-deployments.yaml');
  const runbook = read('deploy/runbooks/session-lineage-rollout.sh');
  const composeRunbook = read('deploy/runbooks/session-lineage-compose-rollout.sh');
  const override = read('deploy/production/compose.session-lineage-enabled.yaml');
  const service = read('internal/portal/service.go');
  const authorization = JSON.parse(read('deploy/authorization-entrypoints.json'));

  assert.match(compose, /PORTAL_SESSION_LINEAGE_LOGOUT_ENABLED: \$\{PORTAL_SESSION_LINEAGE_LOGOUT_ENABLED:-false\}/);
  assert.match(production, /PORTAL_SESSION_LINEAGE_LOGOUT_ENABLED: "false"/);
  assert.match(values, /sessionLineageLogoutEnabled: false/);
  assert.equal(schema.properties.portal.properties.sessionLineageLogoutEnabled.type, 'boolean');
  assert.ok(schema.properties.portal.required.includes('sessionLineageLogoutEnabled'));
  assert.match(template, /PORTAL_SESSION_LINEAGE_LOGOUT_ENABLED.*sessionLineageLogoutEnabled/);
  assert.match(runbook, /images\.tokenPortal\.tag=.*@\$digest/);
  assert.match(runbook, /--atomic/);
  assert.match(runbook, /phase1-pod-set-sha256/);
  assert.match(runbook, /phase2-not-before/);
  assert.match(runbook, /require_phase1_evidence[\s\S]*scale_zero[\s\S]*helm_apply true/);
  assert.match(runbook, /scale_zero[\s\S]*helm_apply false/);
  assert.match(runbook, /binary-rollback-not-before/);
  assert.match(runbook, /binary-rollback-check/);
  assert.match(runbook, /metadata\.creationTimestamp/);
  assert.match(runbook, /session-lineage-rollout-lock/);
  assert.match(runbook, /coordination\.k8s\.io\/v1[\s\S]*kind:"Lease"/);
  assert.match(runbook, /kubectl -n "\$namespace" replace -f - -o json/);
  assert.match(runbook, /DeleteOptions[\s\S]*preconditions[\s\S]*uid/);
  assert.match(runbook, /resourceVersion/);
  assert.match(runbook, /renew_lock[\s\S]*replace -f - -o json/);
  assert.match(runbook, /vars\.length===0[\s\S]*vars\.length!==1[\s\S]*Object\.hasOwn\(v,"valueFrom"\)[\s\S]*typeof v\.value!=="string"[\s\S]*v\.value!=="false"/);
  assert.match(runbook, /timeout --signal=TERM --kill-after=30 660 helm upgrade/);
  assert.match(runbook, /helm upgrade "\$release"[\s\S]*--reuse-values/);
  assert.doesNotMatch(runbook, /helm upgrade --install|--preconditions/);
  assert.match(runbook, /port-forward "pod\/\$pod"/);
  assert.match(runbook, /x\.immutable=true/);
  assert.doesNotMatch(runbook, /patch configmap "\$rollback_evidence"/);
  assert.match(runbook, /rollback_time_evidence[\s\S]*time-source-uid[\s\S]*binary-rollback-not-before/);
  assert.match(runbook, /restore_replicas=\$\(replicas\); restore_enabled=false; restore_needed=true[\s\S]*delete configmap "\$rollback_evidence"[\s\S]*scale_zero[\s\S]*helm_apply true/);
  assert.match(runbook, /restore_replicas=\$\(replicas\); restore_enabled=true; restore_needed=true[\s\S]*scale_zero[\s\S]*helm_apply false/);
  assert.match(runbook, /rollout failed; restoring replicas=\$restore_replicas enabled=\$restore_enabled/);
  assert.match(runbook, /items\.length/);
  assert.match(runbook, /activation-generation/);
  assert.match(runbook, /--connect-timeout 2 --max-time 5/);
  assert.match(runbook, /deletionTimestamp/);
  assert.match(runbook, /verify_pods true/);
  assert.match(override, /PORTAL_SESSION_LINEAGE_LOGOUT_ENABLED: "true"/);
  assert.match(service, /"schema_version": 1,[\s\S]*"capable":[\s\S]*"enabled":/);
  assert.ok(authorization.http_policies.some(entry => entry.method === 'GET' && entry.path === '/health/session-lineage' && entry.scope === 'public'));
  assert.match(runbook, /^#!\/usr\/bin\/env bash\nset -euo pipefail/);
  const root = new URL('../../..', import.meta.url);
  const mode = execFileSync('git', ['ls-files', '-s', 'account-platform/deploy/runbooks/session-lineage-rollout.sh'], { cwd: root, encoding: 'utf8' });
  assert.match(mode, /^100755 /);
  assert.match(composeRunbook, /TOKEN_PORTAL_IMAGE="\$image"[\s\S]*phase2/);
  assert.match(composeRunbook, /age_seconds[\s\S]*600/);
  assert.match(composeRunbook, /2592000/);
  assert.match(composeRunbook, /docker image inspect "\$image" --format '\{\{json \.RepoDigests\}\}'/);
  assert.match(composeRunbook, /\.Config\.Image/);
  assert.match(composeRunbook, /umask 077/);
  assert.match(composeRunbook, /--wait --wait-timeout 120/);
  assert.match(composeRunbook, /container_flag_is_disabled[\s\S]*phase1 refused/);
  assert.match(composeRunbook, /safe_create_evidence "\$phase1"[\s\S]*read -r old_id old_image old_image_id old_started old_running <"\$phase1"/);
  assert.match(composeRunbook, /ln "\$temporary" "\$target"/);
  assert.doesNotMatch(composeRunbook, /mv -n/);
  assert.match(composeRunbook, /rm -f "\$rollback"[\s\S]*require_enabled true[\s\S]*safe_replace_evidence "\$activation"/);
  assert.match(composeRunbook, /recorded_activation_id[\s\S]*== "\$activation_id"/);
  const composeMode = execFileSync('git', ['ls-files', '-s', 'account-platform/deploy/runbooks/session-lineage-compose-rollout.sh'], { cwd: root, encoding: 'utf8' });
  assert.match(composeMode, /^100755 /);
});
