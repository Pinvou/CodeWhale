// Controlled instrumentation, not a natural-load benchmark: the owned fixture
// SELECT policy exposes its single account only to the bounded read-only RR
// transaction. All DDL is limited to retainedManagementTokenRepository's unique
// test database; original migration files and production permissions are unchanged.
func TestF04LegacyOverviewBoundedPostgres(t *testing.T) {
	r, ctx := retainedManagementTokenRepository(t)
	// The COUNT transaction and reset probe must use the same runtime connection.
	// Keep the helper's original pool and cleanup; this owned pool closes first.
	boundedConfig := r.pool.Config().Copy()
	boundedConfig.MaxConns = 1
	boundedPool, err := pgxpool.NewWithConfig(ctx, boundedConfig)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(boundedPool.Close)
	boundedRepository := *r
	boundedRepository.pool = boundedPool
	r = &boundedRepository
	var sessionUser string
	var bypass, super bool
	if err := r.pool.QueryRow(ctx, `SELECT current_user,rolbypassrls,rolsuper FROM pg_roles WHERE rolname=current_user`).Scan(&sessionUser, &bypass, &super); err != nil || sessionUser != "token_gateway" || bypass || super {
		t.Fatalf("nonowner runtime guard: user=%s bypass=%v super=%v err=%v", sessionUser, bypass, super, err)
	}
	config := r.pool.Config().ConnConfig.Copy()
	config.User = "token_migrator"
	owner, err := pgx.ConnectConfig(ctx, config)
	if err != nil {
		t.Fatal(err)
	}
	defer owner.Close(context.Background())
	if _, err = owner.Exec(ctx, `SET ROLE token_schema_owner`); err != nil {
		t.Fatal(err)
	}
	var tableOwner string
	var enabled bool
	var policies int
	if err = owner.QueryRow(ctx, `SELECT pg_get_userbyid(relowner),relrowsecurity,(SELECT count(*) FROM pg_policy WHERE polrelid=c.oid) FROM pg_class c WHERE c.oid='token_accounts'::regclass`).Scan(&tableOwner, &enabled, &policies); err != nil || tableOwner != "token_schema_owner" || enabled || policies != 0 {
		t.Fatalf("owned instrumentation guard: owner=%s RLS=%v policies=%d err=%v", tableOwner, enabled, policies, err)
	}
	actor := uuid.New()
	account := uuid.New()
	now := time.Now().UTC()
	if _, err = r.pool.Exec(ctx, `INSERT INTO token_accounts(id,owner_type,owner_id,wallet_id,name,status,default_priority,created_by,created_at,updated_at,management_mode) VALUES($1,'USER',$2,$3,'bounded-overview-fixture','ACTIVE',100,$2,$4,$4,'PLATFORM')`, account, actor, uuid.New(), now); err != nil {
		t.Fatal(err)
	}
	// UUID text is generated by this test, never caller-controlled SQL.
	if _, err = owner.Exec(ctx, `ALTER TABLE token_accounts ENABLE ROW LEVEL SECURITY; CREATE POLICY f04_legacy_bounded_select ON token_accounts FOR SELECT TO token_gateway USING (id='`+account.String()+`'::uuid AND current_setting('statement_timeout')<>'0' AND current_setting('transaction_read_only')='on' AND current_setting('transaction_isolation')='repeatable read')`); err != nil {
		t.Fatal(err)
	}
	h, overviewSubject := f04LegacyOverviewHandler(t, r, []string{"platform.tokens.read", "platform.usage.read"})
	t.Run("bounded-public-count", func(t *testing.T) {
		w := f04LegacyOverviewRequest(h, ctx, false)
		var body map[string]int64
		if w.Code != 200 || json.Unmarshal(w.Body.Bytes(), &body) != nil || len(body) != 9 || body["token_accounts"] != 1 || body["active_accounts"] != 1 {
			t.Fatalf("bounded real COUNT: status=%d body=%s", w.Code, w.Body.String())
		}
	})
	t.Run("transaction-settings-reset", func(t *testing.T) {
		var ro, iso string
		if err := r.pool.QueryRow(ctx, `SELECT current_setting('transaction_read_only'),current_setting('transaction_isolation')`).Scan(&ro, &iso); err != nil || ro != "off" || iso != "read committed" {
			t.Fatalf("transaction settings leaked: read_only=%s isolation=%s err=%v", ro, iso, err)
		}
	})
	t.Run("durable-quota-before-count", func(t *testing.T) {
		// Set the existing subject window exactly at its deployed threshold;
		// the real admission transaction must increment and refuse before COUNT.
		// Seed the current and next database minute to tolerate a boundary crossing,
		// without a private clock, waiting, or an invented lower limit.
		if _, err := r.pool.Exec(ctx, `WITH clock AS MATERIALIZED (SELECT date_trunc('minute',clock_timestamp()) AS minute)
INSERT INTO token_admin_pagination_creation_windows(rate_key,window_start,creation_count)
SELECT $1,clock.minute+step*interval '1 minute',60 FROM clock CROSS JOIN generate_series(0,1) step
ON CONFLICT(rate_key,window_start) DO UPDATE SET creation_count=60`, "overview:subject:"+overviewSubject.String()+":legacy-overview"); err != nil {
			t.Fatal(err)
		}
		w := f04LegacyOverviewRequest(h, ctx, false)
		if w.Code != http.StatusTooManyRequests || w.Header().Get("Retry-After") == "" || !strings.Contains(w.Body.String(), `"RATE_LIMITED"`) {
			t.Fatalf("durable subject quota: status=%d body=%s", w.Code, w.Body.String())
		}
	})
}
